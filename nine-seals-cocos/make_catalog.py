from collections import deque,defaultdict
import random,json,pathlib
root=pathlib.Path(__file__).resolve().parent
TARGET='123456789'
MOVES=[]
for y in range(2):
 for x in range(2):
  idx=(y*3+x,y*3+x+1,(y+1)*3+x+1,(y+1)*3+x)
  for d in (1,-1): MOVES.append((idx,d))
def rotate(p,m):
 a=list(p); ind,d=MOVES[m]
 for k,i in enumerate(ind):a[ind[(k+d)%4]]=p[i]
 return ''.join(a)
seen={TARGET:0}; children=defaultdict(list); todo=deque([TARGET]); parents={}
while todo:
 cur=todo.popleft(); depth=seen[cur]; children[depth].append(cur)
 for m in range(8):
  nxt=rotate(cur,m)
  if nxt not in seen:
   seen[nxt]=depth+1; parents[nxt]=(cur,m^1); todo.append(nxt)
rng=random.Random(19231120)
bank={}
for depth in range(3,11):
 eligible=children[depth][:]
 rng.shuffle(eligible)
 bank[depth]=eligible[:36]
# Save in TS module, derive from curated exact BFS distance.
s='// Generated by make_catalog.py; exact shortest-path distances via complete BFS of 9! states.\nexport const BANK: Record<number, readonly string[]> = '+json.dumps(bank,ensure_ascii=False,separators=(',',':'))+';\n'
out=root/'assets/scripts/core/Catalog.ts';out.parent.mkdir(parents=True,exist_ok=True);out.write_text(s)
(root/'test_data.json').write_text(json.dumps({'bank':bank,'counts':{str(k):len(v) for k,v in children.items()}},ensure_ascii=False))
print('generated',sum(map(len,bank.values())),'puzzles; max optimal',max(seen.values()),'reachable',len(seen))
